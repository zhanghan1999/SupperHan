// scripts/dsh-assets.mjs
// DSH 生成层：把 sync 后的 dist/{commands,agents,skills} + 工具仓 .qoder/rules/*.md
// 翻译成 DSH skill 树（supperH-* → supperh-* 命名降格 + frontmatter 翻译 + 头部注入
// preamble + 红线四件套合成 + AGENTS.md 带标记区块的合并）。
//
// 边界：
//   - 本文件只做"生成/渲染"，不做安装 I/O（写盘、清单清理）——安装由 scripts/setup.mjs
//     --target dsh 承担，复用其清单式清理（supperh-installed.json）。
//   - 输入是 **sync 后的 dist**（占位符已烤成绝对路径、残留已被 sync 阻断），不是裸源码；
//     红线例外：DSH 没有 rules 目录，supperh-rules 直接从工具仓 .qoder/rules/*.md 合成
//     （与 OpenCode 的 instructions 指回工具仓同一哲学，只是 DSH 只能做拷贝件）。
//   - 源文件正文**一字不改**，只在其上注入 preamble —— 这是"共享仓库不被 DSH 污染"的前提。
//
// Usage: 被 scripts/setup.mjs 与 tests/setup-dsh.test.mjs import；无独立 CLI。

import fs   from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';

import { ROLE_CN } from './asset-names.mjs';

// ---------- 命名 ----------

/** DSH skill 名 = 资产标识符全小写（supperH- 前缀唯一大写字母是 H，toLowerCase 即精确降格）。 */
export function dshName(id) {
  // 先按**源资产**的命名空间校验（唯一的 H 是大写），再降格：supperH-Bad 这种非合规输入直接拒绝。
  const s = String(id);
  if (!/^supperH-[a-z0-9][a-z0-9-]*$/.test(s)) {
    throw new Error(`dshName: ${id} 不是合法 supperH 资产名（须 ^supperH-[a-z0-9][a-z0-9-]*$，H 之外全小写）`);
  }
  return s.toLowerCase();
}

// ---------- 常量 ----------

/** 资产 → DSH skill 形态：command（手势）/ agent（角色）/ protocol（协议）。 */
const SKILL_KIND = {
  command:  { fm: 'disable-model-invocation: true', comment: 'DSH command 形态' },
  agent:    { fm: 'user-invocable: false',          comment: 'DSH subagent 角色 形态' },
  protocol: { fm: 'user-invocable: false',          comment: 'DSH 流程协议 形态' },
  rules:    { fm: 'user-invocable: false',          comment: 'DSH 红线 形态' },
};
export const DSH_GESTURE_NAMES = ['setup', 'bootstrap', 'init', 'driver', 'bug', 'learn'];

export const AGENTS_BEGIN = '<!-- BEGIN supperH rules (generated by scripts/setup.mjs --target dsh) -->';
export const AGENTS_END   = '<!-- END supperH rules -->';

// ---------- 读取 ----------

/** 把一份源资产（已 sync 的 dist 文件）拆成 { description, body }。 */
export function splitAsset(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---[ \t]*\r?\n?/);
  if (!m) return { description: '', body: text.replace(/\r\n/g, '\n').replace(/\n+$/, '\n') };
  let description = '';
  try {
    const fm = YAML.parse(m[1]);
    description = (fm && typeof fm.description === 'string') ? fm.description : '';
  } catch { description = ''; }
  const body = text.slice(m[0].length).replace(/\r\n/g, '\n');
  return { description, body };
}

/** 列出 dist 里的全部资产：{ id, kind, sourceRel, text }（skill 的 id 取目录名）。 */
export function collectDistAssets(distDir) {
  const out = [];
  const dirs = [
    ['agents',   'agent',    (f) => f.replace(/\.md$/i, '')],
    ['commands', 'command',  (f) => f.replace(/\.md$/i, '')],
    ['skills',   'protocol', (f) => f],
  ];
  for (const [sub, kind, stemOf] of dirs) {
    const dir = path.join(distDir, sub);
    if (!fs.existsSync(dir)) continue;
    if (kind === 'protocol') {
      for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
        if (!d.isDirectory()) continue;
        const f = path.join(dir, d.name, 'SKILL.md');
        if (!fs.existsSync(f)) continue;
        out.push({ id: d.name, kind, sourceRel: `skills/${d.name}/SKILL.md`, text: fs.readFileSync(f, 'utf8') });
      }
    } else {
      for (const f of fs.readdirSync(dir)) {
        if (!/\.md$/i.test(f)) continue;
        out.push({ id: stemOf(f), kind, sourceRel: `${sub}/${f}`, text: fs.readFileSync(path.join(dir, f), 'utf8') });
      }
    }
  }
  return out.sort((a, b) => a.id.localeCompare(b.id));
}

// ---------- preamble（与上轮验证过的形态一致，参数化 toolRoot / sourceRel / 角色名） ----------

const TOOL_MAP_LINE =
  '> **工具映射（Qoder/OpenCode → DSH）**：`question` → `ask_user_question`；派子任务（`task` / agent 派发）→ `subagent`（默认后台；必须拿到结果才能继续时传 `run_in_background: false`），续谈 / 并行用 `subagent_fork` 与 `send_message`；`bash` → `pwsh`；`read` / `edit` / `glob` / `grep` 同名。';
const PERM_LINE =
  '> **权限差异（必须知道）**：源文件 frontmatter 的 `permission:`（`edit: deny` / `bash: allow` / `external_directory: deny` / `task: allow`）与 `mcpServers:` 在 DSH 侧**没有** per-agent 机制 —— DSH 的边界是本会话的文件策略（只读 / 可写沙箱）与审批策略。所以正文要求「只读」「写类互斥」「不得越界写私有根之外」的地方是**流程纪律**：沙箱恰好允许，不等于允许做。';
const REDLINE_LINE = '> **红线**：动手前先 `skill` 加载 `supperh-rules`（= 工具仓 `.qoder/rules/` 四件套全文）。';
const REF_LINE =
  '> **角色与协议引用**：正文里 `supperH-<x>` 这类子 agent 名 = 本机 skill `supperh-<x>`（先 `skill` 加载它的正文 = 角色定义，再把「角色正文 + 本次任务」作为 prompt 交给 `subagent`）；正文里 `skills/supperH-<y>/SKILL.md` 这类协议引用 = skill `supperh-<y>`；`/supperH-<z>` 这类命令名 = 本机手势 `/supperh-<z>`（入口是用户手势，不是模型自调）。一律不要把 `supperH-*` 里的文件名/路径当相对路径去 read —— DSH 侧只有 skill 名可用。';
const ORIG_LINE = (toolRoot) =>
  `> **工具仓原件**：\`${String(toolRoot).split(String.fromCharCode(92)).join('/')}\`（\`commands/\`、\`agents/\`、\`skills/\`、\`.qoder/rules/\` 可直接 read；生成件是拷贝件，原件比它新时以原件为准并提醒用户重跑 setup）。`;
const GEN_COMMENT = (sourceRel, shape) =>
  `<!-- 本文件由 \`node scripts/setup.mjs --target dsh\` 从 \`${sourceRel}\` 生成（${shape}）。不要手改；改源文件后重跑该命令。 -->`;

function commandPreamble({ sourceRel, gesture, toolRoot }) {
  return [
    GEN_COMMENT(sourceRel, SKILL_KIND.command.comment),
    '',
    `> **本机手势**：DSH 的命名强制全小写 kebab-case，所以入口是 \`/${gesture}\`（\`/supperH-*\` 在 DSH 里解析不到）。用户消息里出现该手势时本文已经注入该步骤，**不要再调 \`skill\` 工具重载它**；手势后面的自由文本就是本命令的入参（\`--module\` / \`--flow\` 这类旗标也在其中）。`,
    REF_LINE,
    ORIG_LINE(toolRoot),
    TOOL_MAP_LINE,
    PERM_LINE,
    REDLINE_LINE,
    '',
  ].join('\n');
}

function rolePreamble({ sourceRel, id, role, toolRoot }) {
  return [
    GEN_COMMENT(sourceRel, SKILL_KIND.agent.comment),
    '',
    `> **DSH 用法**：这是子 agent 的角色定义（原 Qoder/OpenCode 的 subagent \`${id}\`，角色「${role}」）。DSH 没有"按文件注册 subagent"的目录：主 agent 用 \`skill\` 加载本文，再把「本文 + 本次任务（项目 code、module、anchor、上下文 JSON 等）」作为 \`subagent\` 工具的 prompt 交给一个新子 agent；需要独立上下文续谈时用 \`subagent_fork\` 启动，之后用 \`send_message\` 追问。`,
    TOOL_MAP_LINE,
    PERM_LINE,
    REDLINE_LINE,
    '',
  ].join('\n');
}

function protocolPreamble({ sourceRel, toolRoot }) {
  return [
    GEN_COMMENT(sourceRel, SKILL_KIND.protocol.comment),
    '',
    '> **DSH 用法**：这是流程协议正文（原 Qoder/OpenCode 插件的 skill），由主 agent 或子 agent 按需 `skill` 加载，不占用手势菜单。',
    REF_LINE,
    ORIG_LINE(toolRoot),
    TOOL_MAP_LINE,
    REDLINE_LINE,
    '',
  ].join('\n');
}

function rulesPreamble({ toolRoot }) {
  return [
    GEN_COMMENT('.qoder/rules/*.md', SKILL_KIND.rules.comment),
    '',
    '> **DSH 用法**：这是红线四件套的全文。Qoder 侧由插件把 `rules/` 每轮注入；DSH 没有 rules 目录，所以它是「按需加载 + `AGENTS.md` 里留入口」——任何 supperH 流程动手前先读完它。',
    REF_LINE,
    ORIG_LINE(toolRoot),
    PERM_LINE,
    '',
  ].join('\n');
}

// ---------- 渲染 ----------

/** frontmatter：description 用 JSON.stringify 产出的双引号标量（内含引号会被正确转义）。 */
function frontmatter({ name, description, kind }) {
  return `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n${SKILL_KIND[kind].fm}\n---`;
}

/** 生成单个 skill 的完整 SKILL.md 文本。 */
export function renderSkill({ id, kind, sourceRel, description, body, toolRoot }) {
  const name = dshName(id);
  let preamble;
  if (kind === 'command') preamble = commandPreamble({ sourceRel, gesture: name, toolRoot });
  else if (kind === 'agent') preamble = rolePreamble({ sourceRel, id, role: ROLE_CN[id] || id, toolRoot });
  else preamble = protocolPreamble({ sourceRel, toolRoot });
  const text = `${frontmatter({ name, description, kind })}\n${preamble}\n${body.replace(/\r\n/g, '\n').replace(/\n+$/, '\n')}`;
  return { name, relPath: `skills/${name}/SKILL.md`, text };
}

/** 合成红线 skill（supperh-rules）：四件套按文件名序拼接，每份前加 `## <文件名>`。 */
export function renderRulesSkill({ rulesDir, toolRoot }) {
  const names = ['00-layers.md', '10-redlines.md', '20-workflow.md', '30-commands.md'];
  const parts = [];
  for (const n of names) {
    const p = path.join(rulesDir, n);
    if (!fs.existsSync(p)) throw new Error(`renderRulesSkill: 缺红线文件 ${p}`);
    parts.push(`## ${n}\n\n${fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '\n')}`);
  }
  const body = parts.join('\n');
  const desc = 'supperH 红线全文（00-layers.md / 10-redlines.md / 20-workflow.md / 30-commands.md）——层职责、exit code 约定、R1–R4 硬红线、流程与命令路由。任何 supperH 流程动手前先加载本 skill。';
  const text = `${frontmatter({ name: 'supperh-rules', description: desc, kind: 'rules' })}\n${rulesPreamble({ toolRoot })}\n${body}\n`;
  return { name: 'supperh-rules', relPath: 'skills/supperh-rules/SKILL.md', text };
}

/** 全部 DSH 产物：22 个资产 skill + 1 个红线 skill。 */
export function generateAll({ distDir, rulesDir, toolRoot }) {
  const skills = [];
  for (const a of collectDistAssets(distDir)) {
    const { description, body } = splitAsset(a.text);
    const kind = a.kind === 'agent' ? 'agent' : (a.kind === 'command' ? 'command' : 'protocol');
    skills.push(renderSkill({ id: a.id, kind, sourceRel: a.sourceRel, description, body, toolRoot }));
  }
  skills.push(renderRulesSkill({ rulesDir, toolRoot }));
  return skills.sort((a, b) => a.name.localeCompare(b.name));
}

// ---------- AGENTS.md 区块 ----------

/** AGENTS.md 里由本工具托管的区块全文。 */
export function renderAgentsBlock({ toolRoot, dshHome }) {
  const gestures = DSH_GESTURE_NAMES.map((g) => `/supperh-${g}`).join('\`、\`');
  const t = String(toolRoot).split(String.fromCharCode(92)).join('/');
  const h = String(dshHome).split(String.fromCharCode(92)).join('/');
  return [
    AGENTS_BEGIN,
    `# supperH · DSH 适配（本区块由 \`node scripts/setup.mjs --target dsh\` 维护，重跑即整块替换；不要手改块内内容）`,
    '',
    `- **入口**：DSH 的 skill 名与 \`/name\` 手势强制全小写 kebab-case，所以本机入口是 \`${gestures}\`（\`/supperH-*\` 在 DSH 里解析不到）。`,
    `- **红线**：任何 supperH 流程动手前先加载 skill \`supperh-rules\`；全文 = 工具仓 \`${t}/.qoder/rules/\` 下的 00-layers / 10-redlines / 20-workflow / 30-commands 四件套。`,
    `- **角色**：Qoder/OpenCode 侧的 subagent \`supperH-<x>\` 在本机是 skill \`supperh-<x>\`（角色定义正文）——先 \`skill\` 加载，再把「角色正文 + 本次任务」交给 \`subagent\` 工具。`,
    `- **工具映射**：\`question\` → \`ask_user_question\`；\`task\` / agent 派发 → \`subagent\`（默认后台；必须拿到结果时 \`run_in_background: false\`）；\`bash\` → \`pwsh\`；\`read\`/\`edit\`/\`glob\`/\`grep\` 同名。`,
    `- **权限**：DSH 没有 per-agent 的 \`permission:\`；源文件里的 \`edit: deny\` / \`external_directory: deny\` 是流程纪律，真实边界是本会话的文件策略（只读 / 可写沙箱）与审批策略。`,
    `- **拷贝件**：命令 / agent / 技能 / 红线在本机都是拷贝件（装到 \`${h}\`）——改了工具仓的 \`commands/ agents/ skills/ .qoder/rules/\` 就要重跑 setup。`,
    AGENTS_END,
  ].join('\n') + '\n';
}

/**
 * 把托管区块合并进 AGENTS.md。
 * 返回 { mode: 'created' | 'appended' | 'replaced', text }；mode=created 时 text 就是新文件全文。
 */
export function mergeAgentsBlock(existing, block) {
  const text = existing.replace(/\r\n/g, '\n');
  const begin = text.indexOf(AGENTS_BEGIN);
  const end = text.indexOf(AGENTS_END);
  if (begin !== -1 && end !== -1 && end > begin) {
    const before = text.slice(0, begin);
    const after = text.slice(end + AGENTS_END.length);
    const mid = before.replace(/[ \t]*\n?$/, '') + (before.trim() ? '\n\n' : '') + block
      + (after.trim() ? '\n\n' : '') + after.replace(/^\n+/, '');
    return { mode: 'replaced', text: mid };
  }
  if (text.trim()) return { mode: 'appended', text: text.replace(/\s+$/, '') + '\n\n' + block };
  return { mode: 'created', text: block };
}
